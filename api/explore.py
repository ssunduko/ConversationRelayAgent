"""Serve the vector-store explorer page.

The page itself is generated by scripts/visualize_index.py — a self-contained
HTML file with the projected vectors baked in. This just serves it, so it works
over the tunnel and behaves like a normal web page rather than a file:// URL.
"""

from __future__ import annotations

import logging
from pathlib import Path

from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse

from core.config import SETTINGS

log = logging.getLogger("relay.explore")

router = APIRouter(tags=["explore"])

PAGE = Path(SETTINGS.knowledge_index_path).with_name("index_explorer.html")


@router.get("/explore")
async def explore() -> FileResponse:
    if not PAGE.exists():
        raise HTTPException(
            404,
            "The explorer page has not been generated yet. "
            "Run: python scripts/visualize_index.py",
        )
    index = Path(SETTINGS.knowledge_index_path)
    if index.exists() and index.stat().st_mtime > PAGE.stat().st_mtime:
        # Stale rather than missing: still serve it, but say so.
        log.warning(
            "%s is older than the index — re-run scripts/visualize_index.py",
            PAGE.name,
        )
    # no-store: the page is regenerated whenever the index changes, and a
    # cached copy showing the wrong document count is worse than a reload.
    return FileResponse(PAGE, media_type="text/html", headers={"Cache-Control": "no-store"})
